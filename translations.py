def tr(key, lang="en"):
    """Возвращает перевод `key` для языка `lang` (fallback — английский/сам ключ)."""
    table = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    value = table.get(key)
    return value if value is not None else key